import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { mkdir } from 'node:fs/promises';
const {chromium}=await import(process.env.DITHER_PLAYWRIGHT_PATH?pathToFileURL(resolve(process.env.DITHER_PLAYWRIGHT_PATH)).href:'playwright');
const browser=await chromium.launch({channel:process.env.DITHER_BROWSER||'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
const ready=()=>page.waitForFunction(()=>document.querySelector('#workspace').getAttribute('aria-busy')==='false');
const input=page.locator('#text-editor textarea');
const count=()=>page.locator('[data-history-state]').count();
const key=async k=>{await page.locator('#workspace').focus();await page.keyboard.press(k);await ready();};
const begin=async()=>{await page.locator('[data-text-action=edit]').click();await input.waitFor({state:'visible'});};
async function property(path,value){const control=page.locator(`[data-path="${path}"]`);if(await control.evaluate(el=>el.tagName==='SELECT'))await control.selectOption(String(value));else await control.fill(String(value));await control.press('Tab');await ready();}
try{
  await page.goto(process.env.DITHER_URL||'http://127.0.0.1:4173/');await page.locator('#new-dialog [data-close]').click();
  await page.locator('[data-action=text]').click();await ready();
  assert.equal(await page.locator('#properties [data-path^="text."]').count(),0);
  assert.equal(await page.locator('#tool-options [data-path^="text."]').count(),8);
  const bounds=await page.locator('[data-handle="1,1"]').evaluate(el=>{
    const g=el.parentElement.getBoundingClientRect();return {x:g.x+g.width/2,y:g.y+g.height*.6};
  });
  await page.mouse.dblclick(bounds.x,bounds.y);await input.waitFor({state:'visible'});
  const before=await count();await input.fill('Live text');await input.press('End');await input.press('Enter');await input.pressSequentially('Second line');
  assert.equal(await input.inputValue(),'Live text\nSecond line');assert.equal(await count(),before);
  await input.dispatchEvent('keydown',{key:'Enter',isComposing:true,ctrlKey:true});assert.ok(await input.isVisible());
  await input.press('Control+Enter');await ready();assert.ok(await input.isHidden());assert.equal(await count(),before+1);
  await key('Control+z');await begin();assert.equal(await input.inputValue(),'Text');await input.press('Escape');
  await key('Control+Shift+z');await begin();assert.equal(await input.inputValue(),'Live text\nSecond line');
  const noOpCount=await count();await input.fill('Discard this draft');await input.press('Escape');await ready();assert.equal(await count(),noOpCount);
  await begin();assert.equal(await input.inputValue(),'Live text\nSecond line');
  await input.fill('Styled draft');
  await property('text.fontSize',64);assert.ok(await input.isVisible());assert.equal(await input.inputValue(),'Styled draft');
  await property('text.fontFamily','Inter');await property('text.fontWeight','900');await property('text.fontStyle','italic');await property('text.align','center');await property('text.lineHeight',1.4);await property('text.letterSpacing',2);await property('text.colour','#ffcc00');
  assert.equal(await input.evaluate(el=>getComputedStyle(el).fontSize),'64px');
  assert.equal(await input.evaluate(el=>getComputedStyle(el).textAlign),'center');
  await mkdir('.test-results',{recursive:true});await page.screenshot({path:'.test-results/text-editing.png'});
  await page.locator('[data-text-action=done]').click();await ready();
  await page.screenshot({path:'.test-results/text-rendered.png'});
  await property('transform.rotation',27);await page.locator('[data-action=flip-x]').click();await page.locator('[data-action=zoom-in]').click();
  await begin();await ready();
  const transformed=await page.locator('#text-editor').evaluate(el=>new DOMMatrix(getComputedStyle(el).transform).isIdentity===false);assert.ok(transformed);
  await input.fill('Transformed text');await page.locator('[data-text-action=done]').click();await ready();
  await page.locator('.layer-select').dblclick();await input.waitFor({state:'visible'});assert.equal(await input.inputValue(),'Transformed text');
  await input.fill('Saved while typing');await input.press('Control+s');await page.getByRole('status').filter({hasText:'Project saved'}).waitFor();
  const saved=await page.evaluate(async()=>{const {listProjects,loadProject}=await import('./js/storage/projects.js');const p=await loadProject((await listProjects())[0].id);const result=p.doc.layers[0];p.assets.dispose();return result;});
  assert.equal(saved.text.content,'Saved while typing');assert.equal(saved.text.fontSize,64);assert.equal(saved.text.fontFamily,'Inter');
  await page.locator('[data-action=canvas]').click();
  await page.locator('.layer-select').dblclick();await input.waitFor({state:'visible'});
  assert.equal(await input.inputValue(),'Saved while typing');
  await input.press('End');await input.pressSequentially('!');
  await input.press(process.platform==='darwin'?'Meta+z':'Control+z');
  assert.equal(await input.inputValue(),'Saved while typing');
  await input.press('Escape');
  await page.locator('[data-path=locked]').check();await page.locator('[data-path=locked]').press('Tab');
  assert.ok(await page.locator('[data-text-action=edit]').isDisabled());
  await page.locator('.layer-select').dblclick();assert.ok(await input.isHidden());
  await page.locator('[data-path=locked]').uncheck();await page.locator('[data-path=locked]').press('Tab');
  await page.locator('[data-layer-action=visibility]').click();assert.ok(await page.locator('[data-text-action=edit]').isDisabled());
  await page.locator('[data-layer-action=visibility]').click();
  await page.locator('[data-tool=eyedropper]').click();assert.equal(await page.locator('#tool-options [data-path^="text."]').count(),0);
  await page.locator('.layer-select').click();assert.equal(await page.locator('#tool-options [data-path^="text."]').count(),8);
  await page.setViewportSize({width:600,height:820});await ready();
  const toolbar=await page.locator('#tool-options').boundingBox();assert.ok(toolbar.x>=0&&toolbar.x+toolbar.width<=600);
  await page.screenshot({path:'.test-results/text-toolbar-narrow.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS typography toolbar, canvas/layer double-click editing, multiline and IME, cancel, history, styling, transforms, save, locks, hidden layers and narrow layout');
}finally{await browser.close();}
